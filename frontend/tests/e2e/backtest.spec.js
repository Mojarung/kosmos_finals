import { test, expect } from '@playwright/test'

test('operator reads measured historical A/B/C check with limits and current chip', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('tab', { name: 'Съёмка', exact: true }).click()
  const panel = page.getByTestId('backtest')
  await expect(panel).toContainText('70 чипов')
  await expect(panel).toContainText('60,1%')
  await expect(panel).toContainText('Текущий чип Nigeria_812045')
  const chart = panel.getByTestId('backtest-chart')
  await expect(chart).toContainText('130,75 млн ₽')
  await expect(chart).toContainText('52,13 млн ₽')
  await expect(chart).toContainText('2,46 млн ₽')
  await expect(chart).toContainText('422,2 тыс. ₽')
  const rows = chart.locator('.backtest-chart-row')
  expect(await rows.count()).toBe(3)
  expect(await rows.nth(0).locator('.backtest-error-bar').evaluate(el => parseFloat(el.style.width))).toBe(100)
  expect(await rows.nth(2).locator('.backtest-cost-bar').evaluate(el => parseFloat(el.style.width))).toBeCloseTo(17.16, 1)
  await page.getByLabel('Бюджет на снимки').press('Home')
  await expect(panel).toContainText('фиксированный тест при 6 500 ₽')
  await expect(chart).toContainText('52,13 млн ₽')
  await panel.getByText('По выборкам и как считали').click()
  await expect(panel).toContainText('55 чипов')
  await expect(panel).toContainText('15 чипов')
  await expect(panel).toContainText('не равна кадру 1 м')
  expect(errors).toEqual([])
})

test('historical chart stays readable on a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: /^EL / }).click()
  await page.getByRole('tab', { name: 'Съёмка', exact: true }).click()
  const chart = page.getByTestId('backtest-chart')
  await expect(chart).toBeVisible()
  await chart.scrollIntoViewIfNeeded()
  const bounds = await chart.boundingBox()
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(390)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
