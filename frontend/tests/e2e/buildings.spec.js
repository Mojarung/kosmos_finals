import { test, expect } from '@playwright/test'

async function open(page, width = 1440) {
  await page.setViewportSize({ width, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  if (width < 1024) await page.getByRole('button', { name: /^EL / }).click()
  await page.getByRole('tab', { name: 'Здания', exact: true }).click()
  await page.getByRole('button', { name: 'Пример: Пайпорта', exact: true }).click()
  await expect(page.getByTestId('building-summary')).toContainText('237 из 908')
  await expect(page.getByTestId('building-summary')).toContainText('671 без оценки')
}

test('real buildings: type, independent rate changes, map, export, persistence', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await open(page)
  await expect(page.locator('.buildings-view')).toContainText('2024-11-01')
  await expect(page.locator('.buildings-view')).toContainText('2026-09-26')
  await page.getByLabel('Фильтр зданий').selectOption('unknown')
  await page.locator('.building-row').first().click()
  await expect(page.getByTestId('building-card')).toContainText('Тип не определён')
  await expect(page.getByTestId('building-card')).toContainText('Нет оценки')
  await page.getByLabel('Тип выбранного здания').selectOption('warehouse')
  await expect(page.getByTestId('building-card')).toContainText('Уточнено пользователем')
  await expect(page.getByTestId('building-summary')).toContainText('238 из 908')
  const loss = await page.locator('.building-loss strong').innerText()
  await page.getByText('Стоимость и повреждение по типам', { exact: true }).click()
  await page.getByLabel('Склад: ставка за м²', { exact: true }).fill('60000')
  await expect(page.getByRole('button', { name: 'Скачать здания и расчёт' })).toBeDisabled()
  await page.getByRole('button', { name: 'Применить ставки', exact: true }).click()
  await expect(page.getByTestId('building-card')).toContainText('60 000')
  await expect(page.locator('.building-loss strong')).not.toHaveText(loss)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('floodvalue-building-rates-v1')).warehouse.cost_rub_m2)).toBe(60000)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать здания и расчёт' }).click()
  expect((await download).suggestedFilename()).toBe('building-damage.zip')
  await page.getByRole('button', { name: 'Закрыть карточку здания' }).click()
  await page.getByText('Стоимость и повреждение по типам', { exact: true }).click()
  await page.getByLabel('Фильтр зданий').selectOption('all')
  await page.locator('.building-row').first().click()
  await page.getByTestId('building-card').scrollIntoViewIfNeeded()
  await expect(page.locator('.journey-card')).toBeHidden({ timeout: 30000 })
  await expect(page.locator('.map-veil')).not.toHaveClass(/\bon\b/, { timeout: 30000 })
  // Focused footprint sits in the centre of the map's padded viewport.
  await page.getByRole('button', { name: 'Закрыть карточку здания' }).click()
  await page.mouse.click(710, 510)
  await expect(page.getByTestId('building-card')).toBeVisible()
  await page.screenshot({ path: '/private/tmp/building-damage-desktop.png' })
  await page.reload()
  await page.getByRole('tab', { name: 'Здания', exact: true }).click()
  await page.getByRole('button', { name: 'Пример: Пайпорта', exact: true }).click()
  await expect(page.getByTestId('building-summary')).toContainText('237 из 908')
  await page.getByText('Стоимость и повреждение по типам', { exact: true }).click()
  await expect(page.getByLabel('Склад: ставка за м²', { exact: true })).toHaveValue('60000')
  expect(errors).toEqual([])
})

test('scene change discards a late building response', async ({ page }) => {
  await open(page)
  let release
  const held = new Promise(resolve => { release = resolve })
  let arrived
  const arrivedPromise = new Promise(resolve => { arrived = resolve })
  await page.route('**/api/buildings/load', async route => {
    const response = await route.fetch()
    arrived()
    await held
    await route.fulfill({ response }).catch(() => {})
  })
  await page.getByRole('button', { name: 'Пример: Пайпорта', exact: true }).click()
  await arrivedPromise
  await page.evaluate(async () => (await import('/src/store.js')).chooseScene('Ghana_313799'))
  release()
  await expect(page.getByTestId('building-summary')).toHaveCount(0)
  await expect(page.locator('.scene-title')).toContainText('Гана')
  await expect(page.getByRole('button', { name: 'Загрузить здания области' })).toBeEnabled()
})

test('mobile layout and GeoJSON upload recover after an error', async ({ page }) => {
  await open(page, 375)
  await expect(page.getByRole('tab', { name: 'Здания', exact: true })).toBeInViewport()
  const overflow = await page.locator('.decision-panel').evaluate(el => el.scrollWidth > el.clientWidth + 1)
  expect(overflow).toBe(false)
  await page.getByLabel('Загрузить контуры GeoJSON').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{}') })
  await expect(page.getByRole('alert')).toContainText('FeatureCollection')
  const fixture = { type: 'FeatureCollection', features: [{ type: 'Feature', id: 'demo-house', properties: { building: 'house', name: 'Дом пользователя' }, geometry: { type: 'Polygon', coordinates: [[[-.417,39.427],[-.4168,39.427],[-.4168,39.4272],[-.417,39.4272],[-.417,39.427]]] } }] }
  await page.getByLabel('Загрузить контуры GeoJSON').setInputFiles({ name: 'building.geojson', mimeType: 'application/geo+json', buffer: Buffer.from(JSON.stringify(fixture)) })
  await expect(page.getByTestId('building-summary')).toContainText('1 из 1')
  await page.locator('.building-row').first().click()
  await expect(page.getByTestId('building-card')).toContainText('Дом пользователя')
  await page.getByTestId('building-card').scrollIntoViewIfNeeded()
  await expect(page.locator('.journey-card')).toBeHidden({ timeout: 30000 })
  await expect(page.locator('.map-veil')).not.toHaveClass(/\bon\b/, { timeout: 30000 })
  await page.screenshot({ path: '/private/tmp/building-damage-mobile.png' })
  await page.getByRole('button', { name: 'Показать на карте', exact: true }).click()
  await expect(page.locator('.decision-panel')).toHaveClass(/pill/)
  await page.screenshot({ path: '/private/tmp/building-damage-mobile-map.png' })
})
