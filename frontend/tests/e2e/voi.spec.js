import { test, expect } from '@playwright/test'

test('operator changes visit cost, sees an economic basket and can inspect its zones', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('tab', { name: 'Съёмка', exact: true }).click()
  await page.getByRole('button', { name: 'По ценности информации' }).click()
  const panel = page.getByTestId('voi-panel')
  await expect(panel).toContainText('8 013')
  await expect(panel).toContainText('Чистая польза после данных')
  const chart = panel.getByTestId('voi-chart')
  await expect(chart).toContainText('47,1 тыс. ₽')
  await expect(chart).toContainText('8 тыс. ₽')
  expect(await chart.locator('.voi-benefit-bar').evaluate(el => parseFloat(el.style.width))).toBe(100)
  expect(await chart.locator('.voi-price-bar').evaluate(el => parseFloat(el.style.width))).toBeCloseTo(17.02, 1)
  await expect(panel.locator('.voi-zone')).toHaveCount(4)
  const api = await page.request.get('/api/voi?scene_id=Nigeria_812045&visit_cost=10000&deadline=8')
  const economicPlan = await api.json()
  await expect(page.locator('.asset-marker.covered')).toHaveCount(economicPlan.plan.covered_asset_ids.length)
  await expect(panel.locator('.voi-zone').first()).toContainText('Польза 7 366 ₽')
  await expect(panel.locator('.voi-zone').first()).toContainText('Цена 2 123 ₽')
  await panel.locator('.voi-zone').first().click()
  const exportLink = panel.getByRole('link', { name: 'Скачать расчёт зон и допущения' })
  await expect(exportLink).toHaveAttribute('href', /\/api\/voi\/export\?/)
  const downloadPromise = page.waitForEvent('download')
  await exportLink.click()
  expect((await downloadPromise).suggestedFilename()).toMatch(/\.zip$/)
  await panel.getByRole('button', { name: /Показать остальные зоны/ }).click()
  expect(await panel.locator('.voi-zone').count()).toBeGreaterThan(4)
  await panel.getByLabel('Цена выезда').fill('0')
  await expect(panel).toContainText('Заказ не окупается')
  await expect(panel).toContainText('Цена данных · выведенный бюджет')
  await expect(chart).toContainText('0 ₽')
  await panel.getByLabel('Цена выезда').fill('')
  await expect(panel.getByRole('alert')).toContainText('Введите стоимость выезда')
  await expect(panel.getByLabel('Цена выезда')).toHaveAttribute('aria-invalid', 'true')
  await expect(chart).toHaveCount(0)
  await panel.getByLabel('Цена выезда').fill('10000')
  await expect(panel).toContainText('4 зоны за 8 013 ₽')
  await panel.getByRole('tab', { name: '4 ч' }).click()
  await expect(panel.getByRole('tab', { name: '4 ч' })).toHaveAttribute('aria-selected', 'true')
  await expect(panel).toContainText('4 зоны за 7 075 ₽')
  await panel.getByRole('tab', { name: '8 ч' }).click()
  await panel.getByLabel('Обязательный объект').selectOption({ label: 'Водозабор' })
  await expect(panel.getByLabel('Обязательный объект')).toHaveValue('A10')
  await expect(panel.getByRole('link', { name: 'Скачать расчёт зон и допущения' })).toHaveAttribute('href', /must_cover=A10/)
  await panel.getByLabel('Обязательный объект').selectOption('')
  await panel.getByLabel('Цена выезда').fill('5000')
  await expect(panel).toContainText('РЕШЕНИЕ ПРИ ЭТИХ ДОПУЩЕНИЯХ')
  await page.getByRole('button', { name: 'По бюджету' }).click()
  await expect(page.getByLabel('Бюджет на снимки')).toBeVisible()
  await page.getByRole('button', { name: 'По ценности информации' }).click()
  await expect(panel.getByLabel('Цена выезда')).toHaveValue('5000')
  expect(errors).toEqual([])
})

test('both charts fit tablet and smaller phone widths', async ({ page }) => {
  for (const width of [375, 768]) {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/')
    if (width < 1024) await page.getByRole('button', { name: /^EL / }).click()
    await page.getByRole('tab', { name: 'Съёмка', exact: true }).click()
    await expect(page.getByTestId('backtest-chart')).toBeVisible()
    await page.getByRole('button', { name: 'По ценности информации' }).click()
    await expect(page.getByTestId('voi-chart')).toBeVisible()
    await page.getByTestId('voi-chart').scrollIntoViewIfNeeded()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  }
})

test('economic calculation remains usable on a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: /^EL / }).click()
  await page.getByRole('tab', { name: 'Съёмка', exact: true }).click()
  await page.getByRole('button', { name: 'По ценности информации' }).click()
  const panel = page.getByTestId('voi-panel')
  await expect(panel.getByLabel('Цена выезда')).toBeVisible()
  await expect(panel).toContainText('Чистая польза после данных')
  await panel.getByLabel('Цена выезда').fill('5000')
  await expect(panel).toContainText('РЕШЕНИЕ ПРИ ЭТИХ ДОПУЩЕНИЯХ')
  await expect(panel.getByTestId('voi-chart')).toBeVisible()
  await expect(panel.getByLabel('Обязательный объект')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
